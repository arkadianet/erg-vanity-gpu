//! Generate the 8-bit G_TABLE for windowed k·G.
//!
//! cargo run -p erg-vanity-gpu --bin gen_g_table

use erg_vanity_crypto::secp256k1::point::Point;
use erg_vanity_crypto::secp256k1::scalar::Scalar;
use std::fs;
use std::io::{self, Write};
use std::path::PathBuf;

fn bytes_to_limbs(bytes: &[u8; 32]) -> [u32; 8] {
    let mut limbs = [0u32; 8];
    for (i, limb) in limbs.iter_mut().enumerate() {
        let off = (7 - i) * 4;
        *limb = ((bytes[off] as u32) << 24)
            | ((bytes[off + 1] as u32) << 16)
            | ((bytes[off + 2] as u32) << 8)
            | (bytes[off + 3] as u32);
    }
    limbs
}

fn point_limbs(i: u16) -> ([u32; 8], [u32; 8], [u32; 8]) {
    if i == 0 {
        let one = [1u32, 0, 0, 0, 0, 0, 0, 0];
        return (one, one, [0u32; 8]);
    }
    let mut bytes = [0u8; 32];
    bytes[30] = (i >> 8) as u8;
    bytes[31] = i as u8;
    let scalar = Scalar::from_bytes(&bytes).expect("window scalar in range");
    let point = Point::mul_generator(&scalar);
    let (x, y) = point.to_affine().expect("i*G is not infinity");
    let z_one = [1u32, 0, 0, 0, 0, 0, 0, 0];
    (bytes_to_limbs(&x.to_bytes()), bytes_to_limbs(&y.to_bytes()), z_one)
}

fn write_table<W: Write>(mut out: W) -> io::Result<()> {
    const EXPECTED_GX: [u32; 8] = [
        0x16F81798, 0x59F2815B, 0x2DCE28D9, 0x029BFCDB, 0xCE870B07, 0x55A06295, 0xF9DCBBAC,
        0x79BE667E,
    ];
    const EXPECTED_GY: [u32; 8] = [
        0xFB10D4B8, 0x9C47D08F, 0xA6855419, 0xFD17B448, 0x0E1108A8, 0x5DA4FBFC, 0x26A3C465,
        0x483ADA77,
    ];

    writeln!(out, "// Precomputed table: G_TABLE[i] = i * G for i = 0..255")?;
    writeln!(out, "// Each point = 24 uints (X[8], Y[8], Z[8]), limb 0 = LSB.")?;
    writeln!(out, "// Generated by: cargo run -p erg-vanity-gpu --bin gen_g_table")?;
    writeln!(out, "__constant uint G_TABLE[256][24] = {{")?;

    for i in 0..256u16 {
        let (x, y, z) = point_limbs(i);
        if i == 1 {
            assert_eq!(x, EXPECTED_GX, "1*G X mismatch");
            assert_eq!(y, EXPECTED_GY, "1*G Y mismatch");
            eprintln!("1*G matches kernel GX/GY");
        }
        write!(out, "    {{")?;
        for (j, limb) in x.iter().chain(y.iter()).chain(z.iter()).enumerate() {
            if j > 0 {
                write!(out, ",")?;
            }
            write!(out, " {limb:#010X}u")?;
        }
        if i < 255 {
            writeln!(out, " }},")?;
        } else {
            writeln!(out, " }}")?;
        }
    }
    writeln!(out, "}};")?;
    Ok(())
}

fn main() {
    let dest = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("kernels/g_table.cl");
    let mut buf = Vec::new();
    write_table(&mut buf).unwrap();
    fs::write(&dest, buf).unwrap();
    eprintln!("wrote {}", dest.display());
}
